import { type ReactNode } from "react";

// Line icons for the primitives (Lucide paths, 24×24, stroke = current colour). Decorative: the
// text next to each one carries the meaning.

function Icon({ children, className }: { children: ReactNode; className?: string }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

